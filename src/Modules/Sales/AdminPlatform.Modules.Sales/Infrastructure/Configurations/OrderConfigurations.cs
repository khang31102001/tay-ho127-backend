internal sealed class PaymentConfiguration : IEntityTypeConfiguration<Payment>
{
    public void Configure(EntityTypeBuilder<Payment> builder)
    {
        builder.ToTable("payments", table => table.HasCheckConstraint("ck_payments_amount_non_negative", "amount >= 0"));
        builder.HasKey(p => p.Id);
        builder.Property(p => p.RowVersion).IsRowVersion();

        builder.Property(p => p.OrderCode).HasMaxLength(64).IsRequired();
        builder.Property(p => p.PaymentMethodCode).HasMaxLength(PaymentMethod.MaxCodeLength).IsRequired();
        builder.Property(p => p.PaymentMethodLabel).HasMaxLength(PaymentMethod.MaxNameLength).IsRequired();
        builder.Property(p => p.Amount).HasPrecision(12, 2);
        builder.Property(p => p.Status).HasConversion(new EnumWireConverter<PaymentStatus>()).HasMaxLength(16).IsRequired();
        builder.Property(p => p.TransactionId).HasMaxLength(200);
        builder.Property(p => p.Gateway).HasMaxLength(200);
        builder.Property(p => p.GatewayReference).HasMaxLength(200);

        // One payment per order today; a unique index also guards against a double insert.
        builder.HasIndex(p => p.OrderId).IsUnique();
        builder.HasIndex(p => new { p.Status, p.CreatedAtUtc });

        builder.HasOne<Order>().WithMany().HasForeignKey(p => p.OrderId).OnDelete(DeleteBehavior.Cascade);
        builder.HasMany(p => p.Transactions).WithOne().HasForeignKey(t => t.PaymentId).OnDelete(DeleteBehavior.Cascade);
        builder.Navigation(p => p.Transactions).HasField("_transactions");
    }
}

