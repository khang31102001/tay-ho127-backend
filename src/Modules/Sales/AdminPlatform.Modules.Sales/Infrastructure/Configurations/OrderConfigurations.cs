namespace AdminPlatform.Modules.Sales.Infrastructure.Configurations;

internal sealed class OrderConfiguration : IEntityTypeConfiguration<Order>
{
    public void Configure(EntityTypeBuilder<Order> builder)
    {
        builder.ToTable("orders", table =>
        {
            table.HasCheckConstraint("ck_orders_amounts_non_negative",
                "subtotal >= 0 AND discount >= 0 AND shipping_discount >= 0 AND delivery_fee >= 0 AND total_amount >= 0");
            table.HasCheckConstraint("ck_orders_total_matches",
                "total_amount = subtotal - discount + delivery_fee - shipping_discount");
        });
        builder.HasKey(o => o.Id);
        builder.Property(o => o.RowVersion).IsRowVersion();

        builder.Property(o => o.OrderCode).HasMaxLength(64).IsRequired();
        builder.HasIndex(o => o.OrderCode).IsUnique();
        builder.Property(o => o.IdempotencyKey).HasMaxLength(100);
        builder.HasIndex(o => o.IdempotencyKey).IsUnique().HasFilter("idempotency_key IS NOT NULL");

        builder.Property(o => o.CustomerName).HasMaxLength(Order.MaxNameLength).IsRequired();
        builder.Property(o => o.Phone).HasMaxLength(20).IsRequired();
        builder.Property(o => o.Email).HasMaxLength(Order.MaxEmailLength);
        builder.Property(o => o.DeliveryAddressSnapshot).HasMaxLength(Order.MaxAddressLength).IsRequired();
        builder.Property(o => o.PaymentMethodCode).HasMaxLength(PaymentMethod.MaxCodeLength).IsRequired();
        builder.Property(o => o.PaymentMethodLabel).HasMaxLength(PaymentMethod.MaxNameLength).IsRequired();
        builder.Property(o => o.DeliveryMethodCode).HasMaxLength(DeliveryMethod.MaxCodeLength).IsRequired();
        builder.Property(o => o.DeliveryMethodLabel).HasMaxLength(DeliveryMethod.MaxNameLength).IsRequired();

        builder.Property(o => o.Subtotal).HasPrecision(12, 2);
        builder.Property(o => o.Discount).HasPrecision(12, 2);
        builder.Property(o => o.DiscountCode).HasMaxLength(64);
        builder.Property(o => o.ShippingDiscount).HasPrecision(12, 2);
        builder.Property(o => o.DeliveryFee).HasPrecision(12, 2);
        builder.Property(o => o.TotalAmount).HasPrecision(12, 2);

        builder.Property(o => o.OrderStatus).HasConversion(new EnumWireConverter<OrderStatus>()).HasMaxLength(16).IsRequired();
        builder.Property(o => o.PaymentStatus).HasConversion(new EnumWireConverter<PaymentStatus>()).HasMaxLength(16).IsRequired();
        builder.Property(o => o.CustomerNote).HasMaxLength(Order.MaxNoteLength);

        builder.HasIndex(o => o.CustomerId);
        builder.HasIndex(o => o.Phone);
        builder.HasIndex(o => o.CreatedAtUtc);
        builder.HasIndex(o => new { o.OrderStatus, o.CreatedAtUtc });

        builder.HasMany(o => o.Items).WithOne().HasForeignKey(i => i.OrderId).OnDelete(DeleteBehavior.Cascade);
        builder.Navigation(o => o.Items).HasField("_items");
        builder.HasMany(o => o.OptionSelections).WithOne().HasForeignKey(s => s.OrderId).OnDelete(DeleteBehavior.Cascade);
        builder.Navigation(o => o.OptionSelections).HasField("_optionSelections");
        builder.HasMany(o => o.StatusHistory).WithOne().HasForeignKey(h => h.OrderId).OnDelete(DeleteBehavior.Cascade);
        builder.Navigation(o => o.StatusHistory).HasField("_statusHistory");
    }
}

internal sealed class OrderItemConfiguration : IEntityTypeConfiguration<OrderItem>
{
    public void Configure(EntityTypeBuilder<OrderItem> builder)
    {
        builder.ToTable("order_items", table =>
        {
            table.HasCheckConstraint("ck_order_items_quantity_positive", "quantity > 0");
            table.HasCheckConstraint("ck_order_items_amounts_non_negative", "unit_price >= 0 AND line_total >= 0");
        });
        builder.HasKey(i => i.Id);
        // Ids are generated by the domain, so EF must insert (not update) lines added to a loaded order.
        builder.Property(i => i.Id).ValueGeneratedNever();

        builder.Property(i => i.ProductName).HasMaxLength(200).IsRequired();
        builder.Property(i => i.ProductImageMediaId).HasMaxLength(200);
        builder.Property(i => i.UnitPrice).HasPrecision(12, 2);
        builder.Property(i => i.LineTotal).HasPrecision(12, 2);
        builder.Property(i => i.ItemNote).HasMaxLength(Order.MaxNoteLength);
        builder.HasIndex(i => i.OrderId);
        builder.HasIndex(i => i.ProductId);

        builder.HasMany(i => i.Modifiers).WithOne().HasForeignKey(m => m.OrderItemId).OnDelete(DeleteBehavior.Cascade);
        builder.Navigation(i => i.Modifiers).HasField("_modifiers");
    }
}

